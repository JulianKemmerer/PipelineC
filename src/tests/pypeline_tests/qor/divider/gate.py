@hw_func
def radix2_div_gates(left: uint32_t, right: uint32_t) -> output_payload_t:
    left_eff: uint32_t = left if right != 0 else 4294967295
    d1: uint32_t = right
    q_out: uint32_t = 0
    remainder: uint32_t = 0
    for i in range(31, -1, -1):
        bits1: uint1_t = left_eff[i]
        s: uint33_t = step_gates(remainder, d1, bits1)
        q1: uint1_t = s[32]
        remainder = s[31:0]
        q_out = concat(q_out[30:0], q1)
    return output_payload_t(v1=q_out, v2=remainder)


